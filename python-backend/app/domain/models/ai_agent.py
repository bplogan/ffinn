"""
AI Agent domain models — core of the framework's code generation capability.
"""
from __future__ import annotations

import uuid
from datetime import datetime
from typing import Optional

from sqlalchemy import Boolean, DateTime, Numeric, Integer, String, Text, ForeignKey
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.types import JSON
from sqlalchemy.orm import Mapped, mapped_column, relationship, synonym
from sqlalchemy.sql import func

from app.infrastructure.database import Base


class AIAgentConfiguration(Base):
    __tablename__ = "ai_agent_configurations"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    tenant_id: Mapped[Optional[uuid.UUID]] = mapped_column(UUID(as_uuid=True), nullable=True)

    # Source Control
    source_control_provider: Mapped[str] = mapped_column(String(50), default="")
    repository_url: Mapped[str] = mapped_column(String(500), default="")
    default_branch: Mapped[str] = mapped_column(String(100), default="main")
    encrypted_access_token: Mapped[str] = mapped_column(Text, default="")

    # AI Provider. When provider_id is set, the key/endpoint/model come from that
    # saved AIProviderConfiguration at generation time; the legacy per-agent copies
    # below are only used by agents created before provider linking existed.
    provider_id: Mapped[Optional[uuid.UUID]] = mapped_column(UUID(as_uuid=True), nullable=True)
    ai_provider: Mapped[str] = mapped_column(String(50), default="")
    ai_model: Mapped[str] = mapped_column(String(100), default="")
    azure_deployment_name: Mapped[Optional[str]] = mapped_column(String(200), nullable=True)
    encrypted_api_key: Mapped[str] = mapped_column(Text, default="")
    ai_endpoint: Mapped[Optional[str]] = mapped_column(String(500), nullable=True)

    # Deployment settings
    deployment_mode: Mapped[str] = mapped_column(String(50), default="CreatePR")
    notification_email: Mapped[str] = mapped_column(String(255), default="")
    default_branch_prefix: Mapped[str] = mapped_column(String(100), default="ai-agent/")
    default_commit_message: Mapped[str] = mapped_column(String(500), default="feat: AI-generated code changes")
    default_pr_title: Mapped[str] = mapped_column(String(500), default="AI Agent: Code Generation")
    default_pr_description: Mapped[str] = mapped_column(Text, default="This pull request was automatically generated by the ffinn AI Agent.")

    # Environment settings
    enable_staging_environment: Mapped[bool] = mapped_column(Boolean, default=False)
    staging_branch: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    require_staging_verification: Mapped[bool] = mapped_column(Boolean, default=True)

    # Agent identity. kind="build" is the code-generation agent (one per tenant,
    # flagged is_default and undeletable); kind="assistant" is a chat agent the
    # user sets up with their own instructions and provider.
    kind: Mapped[str] = mapped_column(String(20), default="build", server_default="build")
    is_default: Mapped[bool] = mapped_column(Boolean, default=False, server_default="false")
    description: Mapped[Optional[str]] = mapped_column(String(500), nullable=True)
    system_prompt: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    temperature: Mapped[Optional[float]] = mapped_column(Numeric(3, 2), nullable=True)
    avatar: Mapped[Optional[str]] = mapped_column(String(40), nullable=True)  # emoji or color key

    # Plugin / misc
    is_active: Mapped[bool] = mapped_column(Boolean, default=True)
    name: Mapped[Optional[str]] = mapped_column(String(200), nullable=True)
    staging_workflow_id: Mapped[Optional[str]] = mapped_column(String(200), nullable=True)
    release_workflow_id: Mapped[Optional[str]] = mapped_column(String(200), nullable=True)

    # Azure settings
    azure_webapp_name: Mapped[str] = mapped_column(String(200), default="ffinnframework-api")
    azure_frontend_webapp_name: Mapped[str] = mapped_column(String(200), default="ffinnframework")
    azure_resource_group: Mapped[str] = mapped_column(String(200), default="ffinnframework")
    azure_postgres_server: Mapped[str] = mapped_column(String(200), default="ffinn")
    api_base_url: Mapped[str] = mapped_column(String(500), default="")

    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), onupdate=func.now())
    created_by_id: Mapped[Optional[uuid.UUID]] = mapped_column(UUID(as_uuid=True), nullable=True)

    # Backward-compat synonyms (service layer uses the old field names)
    source_control_type = synonym("source_control_provider")
    source_control_token_encrypted = synonym("encrypted_access_token")
    ai_api_key_encrypted = synonym("encrypted_api_key")
    azure_openai_endpoint = synonym("ai_endpoint")

    generations: Mapped[list["AIAgentGeneration"]] = relationship(
        "AIAgentGeneration", back_populates="configuration", lazy="select"
    )


class AIAgentGeneration(Base):
    __tablename__ = "ai_agent_generations"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    configuration_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("ai_agent_configurations.id"), nullable=False
    )
    # Extra fields used by the service layer
    tenant_id: Mapped[Optional[uuid.UUID]] = mapped_column(UUID(as_uuid=True), nullable=True)
    feature_name: Mapped[Optional[str]] = mapped_column(String(500), nullable=True)
    provider_override: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    model_override: Mapped[Optional[str]] = mapped_column(String(200), nullable=True)

    # Request
    user_prompt: Mapped[str] = mapped_column(Text, nullable=False)
    target_scope: Mapped[str] = mapped_column(String(20), default="tenant", server_default="tenant")
    requested_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    requested_by_id: Mapped[Optional[uuid.UUID]] = mapped_column(UUID(as_uuid=True), nullable=True)
    requested_by_email: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)

    # Status
    status: Mapped[str] = mapped_column(String(50), default="Draft")
    current_step: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)

    # AI Response
    generated_files: Mapped[Optional[dict]] = mapped_column(JSON, nullable=True)
    ai_provider: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)
    ai_model: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    selected_provider_id: Mapped[Optional[uuid.UUID]] = mapped_column(UUID(as_uuid=True), nullable=True)
    tokens_used: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)
    estimated_cost: Mapped[Optional[float]] = mapped_column(Numeric(10, 4), nullable=True)
    generated_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    error_message: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    error_step: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)

    # Validation
    validation_passed: Mapped[Optional[bool]] = mapped_column(Boolean, nullable=True)
    validation_errors: Mapped[Optional[dict]] = mapped_column(JSON, nullable=True)
    auto_fix_report: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    iteration_number: Mapped[int] = mapped_column(Integer, default=1)
    parent_generation_id: Mapped[Optional[uuid.UUID]] = mapped_column(UUID(as_uuid=True), nullable=True)

    # Source Control
    branch_name: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)
    commit_sha: Mapped[Optional[str]] = mapped_column(String(40), nullable=True)
    pull_request_number: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)
    pull_request_url: Mapped[Optional[str]] = mapped_column(String(500), nullable=True)
    committed_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)

    # CI/CD
    pipeline_id: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    pipeline_url: Mapped[Optional[str]] = mapped_column(String(500), nullable=True)
    pipeline_status: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)
    pipeline_started_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    pipeline_completed_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)

    # Staging
    staging_url: Mapped[Optional[str]] = mapped_column(String(500), nullable=True)
    staging_frontend_url: Mapped[Optional[str]] = mapped_column(String(500), nullable=True)
    staging_deployed_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    staging_build_status: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)
    staging_build_log: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    staging_health_check_status: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)

    # Code Review
    code_review_status: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)

    # Scheduled Release
    scheduled_release_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    scheduled_release_by_id: Mapped[Optional[uuid.UUID]] = mapped_column(UUID(as_uuid=True), nullable=True)
    scheduled_release_by_email: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)
    scheduled_release_notes: Mapped[Optional[str]] = mapped_column(String(1000), nullable=True)
    scheduled_release_timezone: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)

    # Release
    released_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    released_by_id: Mapped[Optional[uuid.UUID]] = mapped_column(UUID(as_uuid=True), nullable=True)
    released_by_email: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)
    release_notes: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    reverted_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    revert_reason: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Audit
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), onupdate=func.now())

    # Backward-compat synonyms
    config_id = synonym("configuration_id")
    user_id = synonym("requested_by_id")
    pr_number = synonym("pull_request_number")
    pr_url = synonym("pull_request_url")
    build_url = synonym("pipeline_url")

    @property
    def code_review_passed(self) -> Optional[bool]:
        if self.code_review_status == "Approved":
            return True
        if self.code_review_status in ("Rejected", "ChangesRequested"):
            return False
        return None

    configuration: Mapped["AIAgentConfiguration"] = relationship(
        "AIAgentConfiguration", back_populates="generations", lazy="select"
    )
    progress_events: Mapped[list["AIAgentProgressEvent"]] = relationship(
        "AIAgentProgressEvent", back_populates="generation", lazy="select",
        order_by="AIAgentProgressEvent.created_at"
    )


class AIAgentProgressEvent(Base):
    __tablename__ = "ai_agent_progress_events"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    generation_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("ai_agent_generations.id", ondelete="CASCADE"), nullable=False
    )
    event_type: Mapped[str] = mapped_column(String(50), nullable=False)
    message: Mapped[str] = mapped_column(Text, nullable=False)
    detail: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    step: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    percentage: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())

    generation: Mapped["AIAgentGeneration"] = relationship(
        "AIAgentGeneration", back_populates="progress_events"
    )


